    # PHASE 3.1: ADVANCED VALIDATION METHODS
    # =========================================================================

    def parse_and_validate_move_advanced(self, move_str: str) -> AdvancedLegalityReport:
        """
        Parse and validate a move with advanced quality assessment.
        
        Args:
            move_str: Move in algebraic notation
            
        Returns:
            AdvancedLegalityReport with quality hints and suggestions
        """
        original_move_str = move_str
        move_str = move_str.strip()
        
        # Try notation correction first
        corrected = self._try_correct_notation(move_str)
        if corrected and corrected != move_str:
            logger.debug(f"Corrected notation: '{move_str}' -> '{corrected}'")
            move_str = corrected
        
        # Strip annotations for parsing
        move_str_clean = move_str.rstrip("+#?!").strip()
        
        # Check notation validity
        if not self.validate_move_notation(move_str_clean):
            # Generate candidates for similar moves
            candidates = self._suggest_similar_moves(original_move_str)
            return AdvancedLegalityReport(
                is_legal=False,
                error_message=f"Invalid notation: '{original_move_str}'",
                candidates=candidates,
                repair_suggestion=candidates[0].san if candidates else None,
                issues=[ValidationIssue(
                    severity=ValidationSeverity.ERROR,
                    message=f"Notation '{original_move_str}' doesn't match any known pattern",
                    move_san=original_move_str,
                    suggested_fixes=[c.san for c in candidates[:3]],
                    candidates=candidates[:5],
                )]
            )
        
        try:
            move = self.board.parse_san(move_str_clean)
            
            if move not in self.board.legal_moves:
                candidates = self._suggest_similar_moves(original_move_str)
                return AdvancedLegalityReport(
                    is_legal=False,
                    error_message=f"Illegal move: '{original_move_str}'",
                    position_fen=self.board.fen(),
                    candidates=candidates,
                    repair_suggestion=candidates[0].san if candidates else None,
                    issues=[ValidationIssue(
                        severity=ValidationSeverity.ERROR,
                        message=f"Move '{original_move_str}' is not legal in this position",
                        move_san=original_move_str,
                        position_fen=self.board.fen(),
                        suggested_fixes=[c.san for c in candidates[:3]],
                        candidates=candidates[:5],
                    )]
                )
            
            # Move is legal - assess quality
            quality_hint = self._assess_move_quality(move)
            
            return AdvancedLegalityReport(
                is_legal=True,
                move_object=move,
                position_fen=self.board.fen(),
                quality_hint=quality_hint,
            )
            
        except chess.AmbiguousMoveError as e:
            # Move notation is ambiguous
            candidates = self._resolve_ambiguous_move(move_str_clean)
            return AdvancedLegalityReport(
                is_legal=False,
                error_message=f"Ambiguous move: '{original_move_str}'. Specify the piece more precisely.",
                position_fen=self.board.fen(),
                candidates=candidates,
                repair_suggestion=candidates[0].san if candidates else None,
                issues=[ValidationIssue(
                    severity=ValidationSeverity.ERROR,
                    message=f"Multiple pieces can make this move. Be more specific.",
                    move_san=original_move_str,
                    position_fen=self.board.fen(),
                    suggested_fixes=[c.san for c in candidates],
                    candidates=candidates,
                )]
            )
        except Exception as e:
            candidates = self._suggest_similar_moves(original_move_str)
            return AdvancedLegalityReport(
                is_legal=False,
                error_message=f"Parse error: {str(e)}",
                position_fen=self.board.fen(),
                candidates=candidates,
                repair_suggestion=candidates[0].san if candidates else None,
            )

    def validate_game_pgn_advanced(self, pgn_text: str) -> GameValidationReport:
        """
        Validate an entire game with detailed reporting.
        
        Args:
            pgn_text: Full PGN game text
            
        Returns:
            GameValidationReport with full details
        """
        issues = []
        errors = []
        move_count = 0
        quality_summary: Dict[str, int] = {}
        
        self.reset_board()
        
        # Extract movetext
        pgn_content = pgn_text.split("\n\n", 1)
        movetext = pgn_content[1].strip() if len(pgn_content) > 1 else pgn_text.strip()
        
        lines = movetext.split("\n")
        movetext_lines = [line for line in lines if not line.strip().startswith("[")]
        movetext = " ".join(movetext_lines).strip()
        
        if not movetext:
            return GameValidationReport(
                is_valid=False,
                errors=["No moves found in PGN"],
                issues=[ValidationIssue(
                    severity=ValidationSeverity.ERROR,
                    message="PGN contains no moves",
                )],
            )
        
        extracted_moves = self._extract_moves_from_pgn(movetext)
        
        for i, move_str in enumerate(extracted_moves):
            report = self.parse_and_validate_move_advanced(move_str)
            
            if not report.is_legal:
                errors.append(f"Move {i+1}: {report.error_message}")
                issues.append(ValidationIssue(
                    severity=ValidationSeverity.ERROR,
                    message=report.error_message or "Unknown error",
                    move_number=i + 1,
                    move_san=move_str,
                    position_fen=report.position_fen,
                    candidates=report.candidates,
                ))
                
                return GameValidationReport(
                    is_valid=False,
                    errors=errors,
                    issues=issues,
                    move_count=move_count,
                    final_position=self.board.fen(),
                    quality_summary=quality_summary,
                )
            
            # Track quality
            if report.quality_hint:
                classification = report.quality_hint.classification.value
                quality_summary[classification] = quality_summary.get(classification, 0) + 1
            
            # Apply the move
            self.apply_move(report.move_object)
            move_count += 1
        
        # Determine game result
        game_result = self.get_game_status()
        
        return GameValidationReport(
            is_valid=True,
            errors=[],
            issues=issues,
            move_count=move_count,
            final_position=self.board.fen(),
            game_result=game_result,
            quality_summary=quality_summary,
        )

    def _try_correct_notation(self, move_str: str) -> Optional[str]:
        """
        Try to correct common notation errors.
        
        Args:
            move_str: Potentially malformed move string
            
        Returns:
            Corrected move string or None
        """
        # Direct replacements
        if move_str.lower() in self.NOTATION_CORRECTIONS:
            return self.NOTATION_CORRECTIONS[move_str.lower()]
        
        # Common pattern fixes
        # "Ke8" when meaning "e8" for pawn
        # Extra spaces
        move_str = move_str.strip().replace(" ", "")
        
        # Lowercase piece letters
        if move_str and move_str[0] in "kqrbn":
            move_str = move_str[0].upper() + move_str[1:]
        
        return move_str

    def _suggest_similar_moves(self, failed_move: str) -> List[CandidateMove]:
        """
        Suggest legal moves similar to the failed move.
        
        Args:
            failed_move: The move that failed validation
            
        Returns:
            List of candidate moves sorted by similarity
        """
        candidates = []
        failed_clean = failed_move.strip().rstrip("+#?!").lower()
        
        for legal_move in self.board.legal_moves:
            san = self.board.san(legal_move)
            san_clean = san.rstrip("+#").lower()
            
            # Calculate similarity
            similarity = self._calculate_move_similarity(failed_clean, san_clean)
            
            if similarity > 0.3:  # Threshold for relevance
                reason = self._explain_move_suggestion(legal_move, failed_move)
                candidates.append(CandidateMove(
                    move=legal_move,
                    san=san,
                    reason=reason,
                    similarity_score=similarity,
                ))
        
        # Sort by similarity
        candidates.sort(key=lambda c: c.similarity_score, reverse=True)
        
        # If no similar moves, just return top legal moves
        if not candidates:
            for i, legal_move in enumerate(self.board.legal_moves):
                if i >= 5:
                    break
                san = self.board.san(legal_move)
                candidates.append(CandidateMove(
                    move=legal_move,
                    san=san,
                    reason="Legal alternative",
                    similarity_score=0.1,
                ))
        
        return candidates[:5]

    def _calculate_move_similarity(self, move1: str, move2: str) -> float:
        """Calculate string similarity between two moves."""
        if not move1 or not move2:
            return 0.0
        
        # Exact match
        if move1 == move2:
            return 1.0
        
        # Character overlap
        set1 = set(move1)
        set2 = set(move2)
        overlap = len(set1 & set2)
        total = len(set1 | set2)
        
        jaccard = overlap / total if total > 0 else 0
        
        # Length similarity
        len_sim = 1 - abs(len(move1) - len(move2)) / max(len(move1), len(move2))
        
        # Prefix match bonus
        prefix_bonus = 0
        for i in range(min(len(move1), len(move2))):
            if move1[i] == move2[i]:
                prefix_bonus += 0.1
            else:
                break
        
        return min(1.0, jaccard * 0.4 + len_sim * 0.3 + prefix_bonus)

    def _explain_move_suggestion(self, move: chess.Move, failed_move: str) -> str:
        """Generate explanation for why a move is suggested."""
        san = self.board.san(move)
        
        # Check if same piece type mentioned
        failed_upper = failed_move.upper()
        
        if self.board.is_capture(move):
            return f"Legal capture on {chess.square_name(move.to_square)}"
        
        if "O-O" in failed_move.upper() and self.board.is_castling(move):
            return "Castling move"
        
        piece = self.board.piece_at(move.from_square)
        if piece:
            piece_name = chess.piece_name(piece.piece_type).capitalize()
            if piece_name[0].upper() in failed_upper:
                return f"Alternative {piece_name} move"
        
        return "Legal move in position"

    def _resolve_ambiguous_move(self, move_str: str) -> List[CandidateMove]:
        """
        Resolve an ambiguous move by listing all possibilities.
        
        Args:
            move_str: Ambiguous move notation
            
        Returns:
            List of possible interpretations
        """
        candidates = []
        
        # Try to identify the piece and target square
        piece_char = move_str[0] if move_str[0].isupper() else None
        target_file = None
        target_rank = None
        
        # Parse target square from end
        for i in range(len(move_str) - 1, -1, -1):
            if move_str[i] in "12345678":
                target_rank = int(move_str[i])
                if i > 0 and move_str[i-1] in "abcdefgh":
                    target_file = move_str[i-1]
                break
        
        if target_file and target_rank:
            target_square = chess.parse_square(f"{target_file}{target_rank}")
            
            for legal_move in self.board.legal_moves:
                if legal_move.to_square == target_square:
                    piece = self.board.piece_at(legal_move.from_square)
                    if piece:
                        if piece_char is None or piece.symbol().upper() == piece_char:
                            san = self.board.san(legal_move)
                            from_sq = chess.square_name(legal_move.from_square)
                            candidates.append(CandidateMove(
                                move=legal_move,
                                san=san,
                                reason=f"From {from_sq}",
                                similarity_score=0.9,
                            ))
        
        return candidates

    def _assess_move_quality(self, move: chess.Move) -> MoveQualityHint:
        """
        Assess the quality characteristics of a legal move.
        
        Args:
            move: Valid chess.Move object
            
        Returns:
            MoveQualityHint with move characteristics
        """
        is_check = False
        creates_threat = False
        tactical_motifs = []
        quality_score = 50.0  # Baseline
        
        # Basic properties
        is_capture = self.board.is_capture(move)
        is_castling = self.board.is_castling(move)
        is_promotion = move.promotion is not None
        is_en_passant = self.board.is_en_passant(move)
        
        # Captured piece value
        captured_piece = self.board.piece_at(move.to_square)
        captured_value = self.PIECE_VALUES.get(captured_piece.piece_type, 0) if captured_piece else 0
        
        # Apply move temporarily to check effects
        self.board.push(move)
        
        is_check = self.board.is_check()
        is_checkmate = self.board.is_checkmate()
        
        # Detect tactical patterns
        if is_check:
            quality_score += 10
            if is_checkmate:
                quality_score += 50
                tactical_motifs.append(TacticalMotif.BACK_RANK) if self._is_back_rank_mate() else None
        
        if is_capture:
            quality_score += min(20, captured_value / 50)
        
        if is_promotion:
            quality_score += 25
        
        if is_castling:
            quality_score += 8  # Development bonus
        
        # Check for created threats (new attacks on opponent's pieces)
        creates_threat = self._creates_new_threat(move)
        if creates_threat:
            quality_score += 5
        
        # Detect double check
        if is_check and self._is_double_check():
            tactical_motifs.append(TacticalMotif.DOUBLE_CHECK)
            quality_score += 15
        
        # Detect discovered attack
        if self._is_discovered_attack(move):
            tactical_motifs.append(TacticalMotif.DISCOVERED_ATTACK)
            quality_score += 10
        
        self.board.pop()  # Undo the move
        
        # Classify the move
        if is_checkmate:
            classification = MoveClassification.TACTICAL
        elif is_check or is_capture:
            classification = MoveClassification.FORCING
        elif creates_threat or tactical_motifs:
            classification = MoveClassification.TACTICAL
        elif self.board.fullmove_number <= 10:
            classification = MoveClassification.DEVELOPING
        else:
            classification = MoveClassification.QUIET
        
        return MoveQualityHint(
            classification=classification,
            is_check=is_check,
            is_capture=is_capture,
            is_castling=is_castling,
            is_promotion=is_promotion,
            is_en_passant=is_en_passant,
            creates_threat=creates_threat,
            tactical_motifs=tactical_motifs,
            attacked_piece_value=captured_value,
            quality_score=min(100, quality_score),
        )

    def _is_back_rank_mate(self) -> bool:
        """Check if the current position is a back rank mate."""
        if not self.board.is_checkmate():
            return False
        
        king_square = self.board.king(self.board.turn)
        if king_square is None:
            return False
        
        king_rank = chess.square_rank(king_square)
        return king_rank == 0 or king_rank == 7

    def _is_double_check(self) -> bool:
        """Check if the current position has a double check."""
        if not self.board.is_check():
            return False
        
        king_square = self.board.king(self.board.turn)
        if king_square is None:
            return False
        
        attackers = self.board.attackers(not self.board.turn, king_square)
        return len(attackers) >= 2

    def _creates_new_threat(self, move: chess.Move) -> bool:
        """Check if a move creates new threats on opponent pieces."""
        # Count attacked pieces before and after
        # This is a simplified check
        moving_piece = self.board.piece_at(move.from_square)
        if moving_piece is None:
            return False
        
        # Check if the destination attacks any valuable pieces
        for target_sq in self.board.attacks(move.to_square):
            target_piece = self.board.piece_at(target_sq)
            if target_piece and target_piece.color != moving_piece.color:
                if target_piece.piece_type != chess.PAWN:
                    return True
        
        return False

    def _is_discovered_attack(self, move: chess.Move) -> bool:
        """Check if a move creates a discovered attack."""
        # Look for pieces that were blocked and are now attacking
        from_square = move.from_square
        
        # Check pieces on same rank/file/diagonal as the piece that moved
        for piece_type in [chess.ROOK, chess.BISHOP, chess.QUEEN]:
            for piece_sq in self.board.pieces(piece_type, self.board.turn):
                if piece_sq == move.to_square:
                    continue
                
                # Check if this piece now attacks through the vacated square
                attacks_before = set()  # Simplified - would need before state
                attacks_after = self.board.attacks(piece_sq)
                
                # If the piece attacks the enemy king or queen, it's likely a discovered attack
                enemy_king = self.board.king(not self.board.turn)
                if enemy_king and enemy_king in attacks_after:
                    return True
        
        return False

    def get_move_candidates(
        self,
        classification: Optional[MoveClassification] = None,
        max_count: int = 10
    ) -> List[CandidateMove]:
        """
        Get candidate moves in current position, optionally filtered.
        
        Args:
            classification: Filter by move type (None for all)
            max_count: Maximum number of candidates
            
        Returns:
            List of CandidateMove objects
        """
        candidates = []
        
        for move in self.board.legal_moves:
            quality = self._assess_move_quality(move)
            
            if classification is None or quality.classification == classification:
                san = self.board.san(move)
                reason = self._describe_move(move, quality)
                
                candidates.append(CandidateMove(
                    move=move,
                    san=san,
                    reason=reason,
                    quality_hint=quality,
                    similarity_score=quality.quality_score / 100,
                ))
        
        # Sort by quality
        candidates.sort(key=lambda c: c.quality_hint.quality_score if c.quality_hint else 0, reverse=True)
        
        return candidates[:max_count]

    def _describe_move(self, move: chess.Move, quality: MoveQualityHint) -> str:
        """Generate human-readable description of a move."""
        descriptions = []
        
        if quality.is_check:
            descriptions.append("Check")
        if quality.is_capture:
            descriptions.append(f"Captures (value: {quality.attacked_piece_value})")
        if quality.is_castling:
            descriptions.append("Castling")
        if quality.is_promotion:
            descriptions.append("Promotion")
        if quality.tactical_motifs:
            descriptions.append(f"Tactics: {', '.join(m.value for m in quality.tactical_motifs)}")
        
        if descriptions:
            return "; ".join(descriptions)
        
        return quality.classification.value.capitalize() + " move"

    def suggest_repairs_for_game(
        self,
        pgn_text: str,
        max_alternatives: int = 3
    ) -> List[Tuple[int, str, List[CandidateMove]]]:
        """
        Analyze a game and suggest repairs for illegal moves.
        
        Args:
            pgn_text: PGN game text (may contain errors)
            max_alternatives: Maximum alternatives per illegal move
            
        Returns:
            List of (move_number, illegal_move, candidates) tuples
        """
        repairs = []
        self.reset_board()
        
        pgn_content = pgn_text.split("\n\n", 1)
        movetext = pgn_content[1].strip() if len(pgn_content) > 1 else pgn_text.strip()
        
        lines = movetext.split("\n")
        movetext_lines = [line for line in lines if not line.strip().startswith("[")]
        movetext = " ".join(movetext_lines).strip()
        
        if not movetext:
            return repairs
        
        extracted_moves = self._extract_moves_from_pgn(movetext)
        
        for i, move_str in enumerate(extracted_moves):
            report = self.parse_and_validate_move_advanced(move_str)
            
            if not report.is_legal:
                candidates = report.candidates[:max_alternatives]
                repairs.append((i + 1, move_str, candidates))
                # Stop at first error since subsequent moves depend on this one
                break
            
            self.apply_move(report.move_object)
        
        return repairs


