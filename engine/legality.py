    """A candidate alternative move."""
    move: chess.Move
    san: str
    reason: str              # Why this move is suggested
    quality_hint: Optional[MoveQualityHint] = None
    similarity_score: float = 0.0  # How similar to original intent
    
    def to_dict(self) -> Dict:
        return {
            "san": self.san,
            "reason": self.reason,
            "similarity_score": self.similarity_score,
        }


