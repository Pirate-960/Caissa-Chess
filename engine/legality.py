class MoveClassification(str, Enum):
    """Classification of move types."""
    TACTICAL = "tactical"           # Captures, checks, direct threats
    POSITIONAL = "positional"       # Piece improvement, pawn structure
    QUIET = "quiet"                 # Non-forcing, strategic moves
    FORCING = "forcing"             # Checks, captures with threat
    DEVELOPING = "developing"       # Piece development in opening
    PROPHYLACTIC = "prophylactic"   # Preventing opponent's plan
    DEFENSIVE = "defensive"         # Defensive necessity


class TacticalMotif(str, Enum):
    """Tactical patterns detected in moves."""
    FORK = "fork"
    PIN = "pin"
    SKEWER = "skewer"
    DISCOVERED_ATTACK = "discovered_attack"
